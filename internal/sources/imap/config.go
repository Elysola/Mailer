// Package imap is the IMAP source component. One instance polls one mailbox
// (optionally with IDLE for real-time delivery), owns its UID cursor, and
// emits core.Event stream entries the pipeline consumes.
package imap

import (
	"fmt"
	"time"
)

// Config is the per-instance configuration. The factory decodes the raw
// component config block into this struct; every field maps to the v2 config
// file under a `type: imap` source entry.
type Config struct {
	// InstanceName is the config-file instance name, set by the factory.
	// It is the identity used in logs, metrics, cursors and the event stream.
	InstanceName string `yaml:"-"`

	Host         string        `yaml:"host"`
	Port         int           `yaml:"port"`
	Username     string        `yaml:"username"`
	Password     string        `yaml:"password"`
	PasswordFile string        `yaml:"password_file"`
	OAuth2       *OAuth2Config `yaml:"oauth2"`
	TLS          bool          `yaml:"tls"`
	Mailbox      string        `yaml:"mailbox"`

	// Idle enables real-time delivery: instead of waiting for the next poll
	// tick, the source keeps an IDLE connection open and polls immediately
	// when the server announces new mail. The poll interval stays in effect
	// as a safety net (and is the only mechanism on servers without IDLE).
	Idle           bool `yaml:"idle"`
	MarkSeen       bool `yaml:"mark_seen"`
	NotifyExisting bool `yaml:"notify_existing"`
	SendID         bool `yaml:"send_id"`
	PreviewLen     int  `yaml:"preview_len"`

	PollInterval time.Duration `yaml:"poll_interval"`
	NoopInterval time.Duration `yaml:"noop_interval"`
}

// OAuth2Config configures XOAUTH2 authentication (Gmail and other providers
// that no longer accept passwords). When set, Password is ignored.
type OAuth2Config struct {
	ClientID         string `yaml:"client_id"`
	ClientSecret     string `yaml:"client_secret"`
	ClientSecretFile string `yaml:"client_secret_file"`
	// TokenFile holds the refresh token. Written by `mailer auth gmail` and
	// read at startup; never generated by the daemon itself.
	TokenFile string `yaml:"token_file"`
	Scope     string `yaml:"scope"`
	TokenURL  string `yaml:"token_url"`
}

// DefaultTokenURL is Google's token endpoint.
const DefaultTokenURL = "https://oauth2.googleapis.com/token"

// DefaultGmailScope grants full IMAP access. It is a *restricted* scope: a
// publicly distributed app would need Google's verification plus a third-party
// security assessment. Self-hosted use does not, but the consent screen must
// stay in Testing (7-day refresh tokens) or Internal (Workspace only).
const DefaultGmailScope = "https://mail.google.com/"

func (o *OAuth2Config) ScopeOrDefault() string {
	if o.Scope != "" {
		return o.Scope
	}
	return DefaultGmailScope
}

func (o *OAuth2Config) TokenURLOrDefault() string {
	if o.TokenURL != "" {
		return o.TokenURL
	}
	return DefaultTokenURL
}

func (c *Config) applyDefaults() {
	if c.Mailbox == "" {
		c.Mailbox = "INBOX"
	}
	if c.Port == 0 {
		if c.TLS {
			c.Port = 993
		} else {
			c.Port = 143
		}
	}
	if c.PreviewLen <= 0 {
		c.PreviewLen = 400
	}
	if c.PollInterval <= 0 {
		c.PollInterval = 60 * time.Second
	}
	if c.NoopInterval <= 0 {
		c.NoopInterval = 30 * time.Second
	}
}

func (c *Config) validate(name string) error {
	if c.Host == "" {
		return fmt.Errorf("source %q: host is required", name)
	}
	if c.Username == "" {
		return fmt.Errorf("source %q: username is required", name)
	}
	if c.OAuth2 == nil {
		if c.Password == "" {
			return fmt.Errorf("source %q: password is required (or configure oauth2)", name)
		}
		return nil
	}
	if c.OAuth2.ClientID == "" {
		return fmt.Errorf("source %q: oauth2.client_id is required", name)
	}
	if c.OAuth2.ClientSecret == "" {
		return fmt.Errorf("source %q: oauth2.client_secret (or client_secret_file) is required", name)
	}
	if c.OAuth2.TokenFile == "" {
		return fmt.Errorf("source %q: oauth2.token_file is required; run `mailer auth gmail` to create it", name)
	}
	return nil
}
